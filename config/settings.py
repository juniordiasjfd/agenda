def _bool_do_ambiente(nome, padrao):
    """Lê uma variável booleana ('True'/'False') do ambiente."""
    valor = os.getenv(nome)
    if valor is None or not valor.strip():
        return padrao
    return valor.strip() == 'True'


def _lista_do_ambiente(valor):
    """Converte uma string separada por vírgula (``ALLOWED_HOSTS``,
    ``CSRF_TRUSTED_ORIGINS``) em lista, removendo espaços nas pontas e itens
    vazios.
    """
    if not valor:
        return []
    return [item.strip() for item in valor.split(',') if item.strip()]


